const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const { chromium } = require("playwright");

(async () => {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    const result = await page.evaluate(() => {
      const canvas = document.createElement("canvas");
      canvas.width = canvas.height = 1024;
      const context = canvas.getContext("2d");
      context.beginPath();
      context.roundRect(0, 0, 1024, 1024, 224);
      context.clip();
      context.fillStyle = "#0b1730";
      context.fillRect(0, 0, 1024, 1024);
      const waveformWidth = 21.85 * 1.1;
      const markerWidth = waveformWidth * 0.9;
      const grid = context.createLinearGradient(0, 0, 0, 1024);
      [[0, 0.0297], [0.3, 0.1188], [0.7, 0.0891], [1, 0.0198]].forEach(([stop, alpha]) => grid.addColorStop(stop, `rgba(255,255,255,${alpha})`));
      context.strokeStyle = grid;
      context.lineWidth = markerWidth;
      for (const position of [152, 332, 512, 872]) {
        context.beginPath();
        context.moveTo(position, 0);
        context.lineTo(position, 1024);
        context.stroke();
      }
      const originalData = "M 0 660 C 32 642 52 654 78 656 C 106 660 118 601 148 584 C 174 569 192 616 218 591 C 244 566 252 506 279 513 C 306 520 322 684 352 694 C 384 705 395 608 430 584 C 466 559 483 579 505 544 C 533 500 548 400 578 388 C 609 374 626 484 649 477 C 667 472 678 425 692 410 C 711 392 726 431 741 472 C 759 521 772 572 797 561 C 825 548 846 420 871 400 C 899 379 927 393 950 379 C 978 365 998 350 1024 332";
      const trace = new Path2D();
      const markerX = 692;
      const cubic = (start, first, second, end, amount) => (1 - amount) ** 3 * start + 3 * (1 - amount) ** 2 * amount * first + 3 * (1 - amount) * amount ** 2 * second + amount ** 3 * end;
      let lower = 0;
      let upper = 1;
      for (let iteration = 0; iteration < 40; iteration++) {
        const first = lower + (upper - lower) / 3;
        const second = upper - (upper - lower) / 3;
        if (cubic(694, 705, 608, 584, first) < cubic(694, 705, 608, 584, second)) lower = first;
        else upper = second;
      }
      const peakAmount = (lower + upper) / 2;
      const peakX = 1024 - cubic(352, 384, 395, 430, peakAmount);
      const markerY = 1024 - cubic(694, 705, 608, 584, peakAmount);
      const shiftX = markerX - peakX;
      const extensionWidth = shiftX + 16;
      const extensionY = 332 - extensionWidth * (18 / 26) * 0.65;
      const extendedData = `${originalData} C ${1024 + extensionWidth / 3} ${332 - extensionWidth / 3 * (18 / 26)} ${1024 + extensionWidth * 2 / 3} ${extensionY} ${1024 + extensionWidth} ${extensionY}`;
      const original = new Path2D(extendedData);
      trace.addPath(original, new DOMMatrix([-1, 0, 0, -1, 1024 + shiftX, 1024]));
      const area = new Path2D(trace);
      area.lineTo(-16, 1024);
      area.lineTo(1024 + shiftX, 1024);
      area.closePath();
      const fill = document.createElement("canvas");
      fill.width = fill.height = 1024;
      const fillContext = fill.getContext("2d");
      const spectrum = fillContext.createLinearGradient(0, 330, 0, 1024);
      spectrum.addColorStop(0, "#168cff");
      spectrum.addColorStop(0.33, "#0044ff");
      spectrum.addColorStop(0.67, "#ff003c");
      spectrum.addColorStop(1, "#ff9900");
      fillContext.fillStyle = spectrum;
      fillContext.fill(area);
      fillContext.globalCompositeOperation = "source-atop";
      const reflection = fillContext.createLinearGradient(80, 350, 850, 1024);
      reflection.addColorStop(0, "rgba(230,242,255,0.26)");
      reflection.addColorStop(0.3, "rgba(230,242,255,0.04)");
      reflection.addColorStop(0.48, "rgba(230,242,255,0.16)");
      reflection.addColorStop(0.64, "rgba(230,242,255,0)");
      reflection.addColorStop(1, "rgba(0,5,20,0.3)");
      fillContext.fillStyle = reflection;
      fillContext.fillRect(0, 0, 1024, 1024);
      fillContext.globalCompositeOperation = "destination-in";
      const fade = fillContext.createLinearGradient(0, 330, 0, 1024);
      fade.addColorStop(0, "rgba(0,0,0,0.72)");
      fade.addColorStop(0.45, "rgba(0,0,0,0.48)");
      fade.addColorStop(1, "rgba(0,0,0,0)");
      fillContext.fillStyle = fade;
      fillContext.fillRect(0, 0, 1024, 1024);
      context.drawImage(fill, 0, 0);
      context.strokeStyle = "#ee8b9d";
      context.lineWidth = markerWidth;
      context.beginPath();
      context.moveTo(markerX, 0);
      context.lineTo(markerX, 1024);
      context.stroke();
      const markerHighlight = context.createLinearGradient(markerX - markerWidth / 2, 0, markerX + markerWidth * 0.375, 0);
      markerHighlight.addColorStop(0, "rgba(80,22,48,0.3)");
      markerHighlight.addColorStop(0.28, "rgba(255,240,245,0.82)");
      markerHighlight.addColorStop(0.5, "rgba(255,240,245,0.22)");
      markerHighlight.addColorStop(1, "rgba(255,224,231,0)");
      context.fillStyle = markerHighlight;
      context.fillRect(markerX - markerWidth / 2, 0, markerWidth * 0.875, 1024);
      context.save();
      context.shadowColor = "rgba(0,5,20,0.6)";
      context.shadowBlur = 12;
      context.shadowOffsetY = 7;
      context.strokeStyle = "#dddddd";
      context.lineWidth = waveformWidth;
      context.lineCap = "round";
      context.lineJoin = "round";
      context.stroke(trace);
      const markerOnTrace = context.isPointInStroke(trace, markerX, markerY);
      const geometry = document.createElementNS("http://www.w3.org/2000/svg", "path");
      geometry.setAttribute("d", extendedData);
      const length = geometry.getTotalLength();
      const steps = Math.ceil(length / 0.75);
      const accent = new Path2D();
      const offset = waveformWidth / 6;
      for (let step = 0; step <= steps; step++) {
        const distance = length * step / steps;
        const point = geometry.getPointAtLength(distance);
        const before = geometry.getPointAtLength(Math.max(0, distance - 0.25));
        const after = geometry.getPointAtLength(Math.min(length, distance + 0.25));
        const tangentX = before.x - after.x;
        const tangentY = before.y - after.y;
        const magnitude = Math.hypot(tangentX, tangentY);
        const horizontal = 1024 + shiftX - point.x - offset * tangentY / magnitude;
        const vertical = 1024 - point.y + offset * tangentX / magnitude;
        if (step === 0) accent.moveTo(horizontal, vertical);
        else accent.lineTo(horizontal, vertical);
      }
      context.shadowColor = "transparent";
      context.strokeStyle = "#ffffff";
      context.lineWidth = 6.3;
      context.stroke(accent);
      context.restore();
      const circleScale = 1.1 * 0.95;
      const glowScale = 1.25 * 1.05 * 1.1;
      const halo = context.createRadialGradient(markerX, markerY, 57.2 * glowScale, markerX, markerY, 88 * glowScale);
      halo.addColorStop(0, "rgba(238,139,157,0.35)");
      halo.addColorStop(0.45, "rgba(238,139,157,0.16)");
      halo.addColorStop(1, "rgba(238,139,157,0)");
      context.save();
      context.filter = `blur(${13.2 * glowScale}px)`;
      context.fillStyle = halo;
      context.beginPath();
      context.arc(markerX, markerY, 88 * glowScale, 0, Math.PI * 2);
      context.fill();
      context.restore();
      const ring = context.createLinearGradient(markerX, markerY - 70.4 * circleScale, markerX, markerY + 70.4 * circleScale);
      ring.addColorStop(0, "rgba(255,190,205,0.85)");
      ring.addColorStop(0.24, "rgba(238,139,157,0.65)");
      ring.addColorStop(0.72, "rgba(158,67,94,0.9)");
      ring.addColorStop(1, "rgba(238,139,157,0.72)");
      const core = context.createRadialGradient(markerX, markerY, 0, markerX, markerY, 44 * circleScale);
      core.addColorStop(0, "#ee8b9d");
      core.addColorStop(0.8, "#ee8b9d");
      core.addColorStop(0.94, "#ffc0cf");
      core.addColorStop(1, "#ee8b9d");
      for (const [radius, color] of [[70.4, ring], [50.6, "rgba(238,139,157,0.45)"], [44, core]]) {
        context.fillStyle = color;
        context.beginPath();
        context.arc(markerX, markerY, radius * circleScale, 0, Math.PI * 2);
        context.fill();
      }
      const sample = (horizontal, vertical) => Array.from(context.getImageData(horizontal, vertical, 1, 1).data);
      return { png: canvas.toDataURL("image/png").split(",")[1], markerWidth, waveformWidth, extensionSlope: (332 - (332 - extensionWidth / 3 * (18 / 26))) / (extensionWidth / 3), peakAligned: Math.abs(peakX + shiftX - markerX) < 0.001, peakIsHighest: markerY <= 1024 - cubic(694, 705, 608, 584, peakAmount - 0.001) && markerY <= 1024 - cubic(694, 705, 608, 584, peakAmount + 0.001), edges: [sample(shiftX, 692)], accent: sample(shiftX - 2, 688), traceBase: sample(shiftX, 700), marker: sample(markerX, markerY), markerLine: sample(markerX + 9, 100), markerHighlight: sample(markerX - 5, 100), ring: sample(markerX + 55, markerY), markerOnTrace, corner: sample(0, 0) };
    });
    result.edges.forEach(pixel => assert.ok(pixel[0] >= 221 && pixel[0] === pixel[1] && pixel[1] === pixel[2] && pixel[3] === 255));
    assert.deepEqual(result.accent, [255, 255, 255, 255]);
    assert.ok(result.markerHighlight[1] > 200);
    assert.deepEqual(result.traceBase, [221, 221, 221, 255]);
    assert.deepEqual(result.marker, [238, 139, 157, 255]);
    assert.deepEqual(result.markerLine, [238, 139, 157, 255]);
    assert.ok(Math.abs(result.markerWidth / result.waveformWidth - 0.9) < 1e-10);
    assert.ok(Math.abs(result.waveformWidth / 21.85 - 1.1) < 1e-10);
    assert.ok(Math.abs(result.extensionSlope - 18 / 26) < 1e-10);
    assert.ok(result.ring[0] > result.ring[1]);
    assert.ok(result.markerOnTrace);
    assert.ok(result.peakAligned && result.peakIsHighest);
    assert.equal(result.corner[3], 0);
    fs.writeFileSync(path.join(__dirname, "16-expanded-blurred-ring.png"), Buffer.from(result.png, "base64"));
    console.log("Glass waveform: light grey base, white highlight, pink marker and transparent corners verified.");
  } finally {
    await browser.close();
  }
})();